"""Unit tests for :mod:`src.graph.exporter`.

The tests use a small hardcoded graph so that Phase 5 is validated
independently of the Phase 1-4 builders. Only topology tensors are expected;
node features (``x``) belong to the Feature Encoder module and must not be
generated by the exporter.
"""

from __future__ import annotations

from copy import deepcopy
from typing import Any

import pytest
import torch

from src.graph.exporter import (
    EDGE_TYPE_TO_INDEX,
    INDEX_TO_EDGE_TYPE,
    export_to_pyg_format,
)


def _tiny_graph() -> dict[str, Any]:
    """Return a valid three-node, two-edge graph in a deliberate order."""

    return {
        "session_id": "sess-export-0001",
        "nodes": [
            {
                "node_id": "node-c",
                "node_type": "proposed_action",
                "session_id": "sess-export-0001",
            },
            {
                "node_id": "node-a",
                "node_type": "user",
                "session_id": "sess-export-0001",
            },
            {
                "node_id": "node-b",
                "node_type": "assistant",
                "session_id": "sess-export-0001",
            },
        ],
        "edges": [
            {
                "source": "node-c",
                "target": "node-a",
                "type": "NEXT_EVENT",
            },
            {
                "source": "node-a",
                "target": "node-b",
                "type": "REQUESTS_TOOL",
            },
        ],
    }


def test_edge_index_has_exact_shape_and_long_dtype() -> None:
    exported = export_to_pyg_format(_tiny_graph())
    edge_index = exported["edge_index"]

    assert isinstance(edge_index, torch.Tensor)
    assert tuple(edge_index.shape) == (2, 2)
    assert edge_index.dtype == torch.long
    assert edge_index.tolist() == [[0, 1], [1, 2]]


def test_edge_type_has_exact_shape_and_long_dtype() -> None:
    exported = export_to_pyg_format(_tiny_graph())
    edge_type = exported["edge_type"]

    assert isinstance(edge_type, torch.Tensor)
    assert tuple(edge_type.shape) == (2,)
    assert edge_type.dtype == torch.long
    assert edge_type.tolist() == [
        EDGE_TYPE_TO_INDEX["NEXT_EVENT"],
        EDGE_TYPE_TO_INDEX["REQUESTS_TOOL"],
    ]


def test_node_mapping_aligns_index_zero_with_first_node() -> None:
    exported = export_to_pyg_format(_tiny_graph())
    node_mapping = exported["node_mapping"]

    assert node_mapping == ["node-c", "node-a", "node-b"]
    assert node_mapping[0] == "node-c"
    assert node_mapping[1] == "node-a"
    assert node_mapping[2] == "node-b"


def test_session_id_is_preserved() -> None:
    graph = _tiny_graph()

    exported = export_to_pyg_format(graph)

    assert exported["session_id"] == graph["session_id"]


def test_no_feature_matrix_is_emitted() -> None:
    exported = export_to_pyg_format(_tiny_graph())

    assert "x" not in exported
    assert set(exported) == {
        "session_id",
        "node_mapping",
        "edge_index",
        "edge_type",
    }


def test_static_edge_type_encoding_covers_all_allowed_types() -> None:
    assert EDGE_TYPE_TO_INDEX == {
        "NEXT_EVENT": 0,
        "RESPONDS_TO": 1,
        "RETRIEVED_FROM": 2,
        "REQUESTS_TOOL": 3,
    }
    assert INDEX_TO_EDGE_TYPE == {
        0: "NEXT_EVENT",
        1: "RESPONDS_TO",
        2: "RETRIEVED_FROM",
        3: "REQUESTS_TOOL",
    }


def test_every_edge_type_is_encoded_using_the_static_mapping() -> None:
    graph = _tiny_graph()
    graph["edges"] = [
        {"source": "node-c", "target": "node-a", "type": "NEXT_EVENT"},
        {"source": "node-a", "target": "node-c", "type": "RESPONDS_TO"},
        {"source": "node-a", "target": "node-b", "type": "RETRIEVED_FROM"},
        {"source": "node-b", "target": "node-c", "type": "REQUESTS_TOOL"},
    ]

    exported = export_to_pyg_format(graph)

    assert exported["edge_type"].tolist() == [0, 1, 2, 3]
    assert tuple(exported["edge_index"].shape) == (2, 4)


def test_empty_graph_returns_empty_topology_tensors() -> None:
    graph = {
        "session_id": "sess-empty-0001",
        "nodes": [],
        "edges": [],
    }

    exported = export_to_pyg_format(graph)

    assert exported["node_mapping"] == []
    assert tuple(exported["edge_index"].shape) == (2, 0)
    assert tuple(exported["edge_type"].shape) == (0,)
    assert exported["edge_index"].dtype == torch.long
    assert exported["edge_type"].dtype == torch.long


def test_zero_edge_graph_keeps_nodes_and_returns_empty_tensors() -> None:
    graph = _tiny_graph()
    graph["edges"] = []

    exported = export_to_pyg_format(graph)

    assert exported["node_mapping"] == ["node-c", "node-a", "node-b"]
    assert tuple(exported["edge_index"].shape) == (2, 0)
    assert tuple(exported["edge_type"].shape) == (0,)


def test_exporter_does_not_mutate_the_input_graph() -> None:
    graph = _tiny_graph()
    original = deepcopy(graph)

    export_to_pyg_format(graph)

    assert graph == original


def test_unknown_edge_type_is_rejected() -> None:
    graph = _tiny_graph()
    graph["edges"].append(
        {
            "source": "node-a",
            "target": "node-b",
            "type": "INFLUENCES",
        }
    )

    with pytest.raises(ValueError, match="unknown edge type"):
        export_to_pyg_format(graph)


def test_dangling_edge_endpoint_is_rejected() -> None:
    graph = _tiny_graph()
    graph["edges"].append(
        {
            "source": "node-a",
            "target": "node-does-not-exist",
            "type": "NEXT_EVENT",
        }
    )

    with pytest.raises(ValueError, match="unknown node"):
        export_to_pyg_format(graph)


def test_duplicate_node_id_is_rejected() -> None:
    graph = _tiny_graph()
    graph["nodes"].append(deepcopy(graph["nodes"][0]))

    with pytest.raises(ValueError, match="duplicate node_id"):
        export_to_pyg_format(graph)


def test_missing_required_graph_key_is_rejected() -> None:
    graph = _tiny_graph()
    del graph["edges"]

    with pytest.raises(ValueError, match="missing required keys"):
        export_to_pyg_format(graph)
